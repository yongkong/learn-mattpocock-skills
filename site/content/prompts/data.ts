/** 用槽位默认值渲染模板(lang 取 "en" | "zh")。 */
export function fillPrompt(p: PromptEntry, lang: "en" | "zh"): string {
  const tpl = lang === "en" ? p.pe : p.pz;
  return tpl.replace(/\{(\w+)\}/g, (_, k: string) => (p.s && p.s[k] ? p.s[k][lang === "en" ? 0 : 1] : k));
}

/** 搜索索引:标题、模板、填充结果、阶段/类别/角色词全部拼进一段小写文本。 */
export function promptIndex(p: PromptEntry): string {
  return [
    p.tz,
    p.te,
    p.pe,
    p.pz,
    fillPrompt(p, "en"),
    fillPrompt(p, "zh"),
    PHASES[p.phase].zh,
    PHASES[p.phase].en,
    CATS[p.cat].zh,
    CATS[p.cat].en,
    p.cat,
    ...(p.roles ?? []).map((r) => `${ROLES[r].zh} ${ROLES[r].en} ${r}`),
    p.why,
  ]
    .join(" ")
    .toLowerCase();
}
