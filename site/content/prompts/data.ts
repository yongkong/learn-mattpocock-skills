export interface PromptEntry {
  id: string;
  phase: PhaseKey;
  cat: CatKey;
  /** 「★ 从这里开始」推荐序号(共 5 条),升序即推荐阅读序。 */
  start?: number;
  roles?: RoleKey[];
  paste?: PasteKey;
  needs?: NeedKey;
  /** 英文标题。 */
  te: string;
  /** 中文标题。 */
  tz: string;
  /** 英文提示词模板,{slot} 为可替换槽位。 */
  pe: string;
  /** 中文翻译模板,槽位名与英文一一对应。 */
  pz: string;
  /** 槽位默认填充:{key: [英文示例, 中文示例]}。 */
  s?: Record<string, [string, string]>;
  /** 为什么有效(中文讲解)。 */
  why: string;
  /** 进阶提示(可选)。 */
  next?: string;
  src: SrcKey;
}

